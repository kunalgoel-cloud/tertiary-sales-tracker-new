_ALIASES = {
    "bengaluru": "bangalore",
    "bombay": "mumbai",
    "calcutta": "kolkata",
    "madras": "chennai",
}


def get_city_coords(raw_city: str):
    """
    Resolve a raw city string (as stored in the sales table) to (lat, lon),
    or None if unmapped. Uses channel_performance_module._norm_city() for
    normalisation so this stays consistent with the rest of the app's city
    matching logic.
    """
    from channel_performance_module import _norm_city
    key = _norm_city(raw_city)
    key = _ALIASES.get(key, key)
    return CITY_COORDS.get(key)
